import random


def random_color():
    colors = [
        "\033[31m",  # Red
        "\033[32m",  # Green
        "\033[33m",  # Yellow
        "\033[34m",  # Blue
        "\033[35m",  # Purple
        "\033[36m",  # Cyan
        "\033[91m",  # Light Red
        "\033[92m",  # Light Green
        "\033[93m",  # Light Yellow
        "\033[94m",  # Light Blue
        "\033[95m",  # Light Purple
        "\033[96m",  # Light Cyan
        "\033[30m",  # Black
        "\033[37m",  # Light Gray
        "\033[90m",  # Dark Gray
    ]
    return random.choice(colors)


# Function to print ASCII art with a random color
def print_random_color(text):
    color = random_color()
    print(color + text + "\033[0m")  # Reset color after printing


